-- =========================================================
-- 7. FUNÇÃO DE ADMIN
-- =========================================================
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
set row_security = off
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role = 'admin'
  );
$$;

-- =========================================================
-- 8. PROTEÇÃO DO CAMPO ROLE
-- =========================================================
-- Impede um cliente autenticado de se transformar em admin
-- alterando o próprio profile pela API.
create or replace function public.protect_profile_role()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  -- Chamadas administrativas do SQL Editor / service role têm auth.uid() nulo.
  if auth.uid() is null then
    return new;
  end if;

  if tg_op = 'INSERT' then
    if coalesce(new.role, 'customer') <> 'customer' and not public.is_admin() then
      raise exception 'Somente administradores podem definir role=admin';
    end if;
  elsif tg_op = 'UPDATE' then
    if new.role is distinct from old.role and not public.is_admin() then
      raise exception 'Somente administradores podem alterar o nível de acesso';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists profiles_protect_role on public.profiles;
create trigger profiles_protect_role
before insert or update on public.profiles
for each row
execute function public.protect_profile_role();

