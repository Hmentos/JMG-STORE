-- 21. GARANTIR QUE O ADMIN POSSA ALTERAR ROLES PELO PAINEL
-- =========================================================
-- A política "Admins can manage profiles" + o trigger de proteção
-- permitem que somente administradores promovam/rebaixem usuários.

-- =========================================================
-- 22. CORREÇÃO DE PERFIS QUE EXISTEM NO AUTH MAS NÃO EM PROFILES
-- =========================================================
-- Nenhuma ação geral é feita aqui para não criar perfis indesejados.
-- A seção 24 abaixo cria/atualiza apenas as 2 contas administrativas.

-- =========================================================
-- 23. OBSERVAÇÃO SOBRE OS 2 ADMINS
-- =========================================================
-- As duas contas precisam existir primeiro em:
-- Supabase > Authentication > Users
--
-- Depois, edite SOMENTE os dois e-mails na seção 24.

-- =========================================================
-- 24. DEFINIR OS 2 ADMINISTRADORES
-- =========================================================
do $$
declare
  admin_emails text[] := array[
    'PRIMEIRO_ADMIN@gmail.com',
    'SEGUNDO_ADMIN@gmail.com'
  ];
  found_count integer;
begin
  -- Se os placeholders não forem alterados, o restante do SQL continua,
  -- mas nenhuma conta é promovida por engano.
  if admin_emails[1] = 'PRIMEIRO_ADMIN@gmail.com'
     or admin_emails[2] = 'SEGUNDO_ADMIN@gmail.com' then
    raise notice 'ATENÇÃO: edite os 2 e-mails da seção 24 antes de configurar os administradores.';
    return;
  end if;

  insert into public.profiles (id,email,full_name,phone,role)
  select
    u.id,
    u.email,
    coalesce(nullif(u.raw_user_meta_data->>'full_name',''),'Administrador'),
    coalesce(u.raw_user_meta_data->>'phone',''),
    'admin'
  from auth.users u
  where lower(u.email) = any (
    array[
      lower(admin_emails[1]),
      lower(admin_emails[2])
    ]
  )
  on conflict (id)
  do update set
    email = excluded.email,
    role = 'admin';

  select count(*)
  into found_count
  from auth.users u
  where lower(u.email) = any (
    array[
      lower(admin_emails[1]),
      lower(admin_emails[2])
    ]
  );

  if found_count < 2 then
    raise notice 'Apenas % das 2 contas foi encontrada em Authentication > Users.', found_count;
  else
    raise notice 'As 2 contas administrativas foram encontradas e configuradas.';
  end if;
end $$;

-- =========================================================
-- 25. CONFERIR ADMINS
-- =========================================================
select
  u.id as auth_id,
  u.email as auth_email,
  p.id as profile_id,
  p.email as profile_email,
  p.full_name,
  p.role
from auth.users u
left join public.profiles p on p.id = u.id
where p.role = 'admin'
order by u.email;

